import assert from 'node:assert/strict';
import {MightyOccupancyGridWorker} from '../js/sdk/occupancy-worker.js';
const messages=[];const listeners={};
globalThis.Worker=class {postMessage(m){messages.push(structuredClone(m));}terminate(){}};
const client=Object.fromEntries(['Image','Depth','Pose','VioState','Reset'].map(k=>['on'+k,fn=>{listeners[k]=fn;return()=>{};}]));
const worker=new MightyOccupancyGridWorker(client,{tofCalibration:{matrix:[]}});
worker._handleWorkerMessage({type:'ready'});
const image={kind:'jpg',data:new Uint8Array([1,2]),timestampNs:1n,acknowledgePreview:()=>{throw Error('UI owns acknowledgment');}};
listeners.Image(image);
assert.equal(messages.at(-1).eventType,'image');
assert.equal(messages.at(-1).value.acknowledgePreview,undefined);
assert.equal(typeof image.acknowledgePreview,'function');
listeners.Image({...image,timestampNs:2n});
assert.equal(messages.at(-1).value.timestampNs,1n);
worker._handleWorkerMessage({type:'frame_done'});
assert.equal(messages.at(-1).value.timestampNs,2n);
worker._handleWorkerMessage({type:'frame_done'});
listeners.Image({kind:'jpg',timestampNs:3n});
assert.equal(worker.workerBusy,false,'drop notifications do not stall worker');
listeners.Depth({timestampNs:2n,depthMm:new Uint16Array([1000])});
assert.equal(messages.at(-1).eventType,'depth');
worker.close();
console.log('Preview callback isolation, backpressure, dropped frames and depth forwarding passed');
